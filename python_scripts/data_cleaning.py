"""
data_cleaning.py
================
Step 1 of the Luxury Housing Sales Analysis pipeline.

Reads the raw ``Luxury_Housing_Bangalore.csv`` (101,000 rows x 18 columns),
repairs every data-quality defect seeded into it, engineers the analytical
columns the dashboard needs, and writes a clean CSV plus a markdown audit of
everything that was changed.

Run:
    python python_scripts/data_cleaning.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))

import config as cfg  # noqa: E402


# --------------------------------------------------------------------------
# Audit trail
# --------------------------------------------------------------------------
class CleaningReport:
    """Collects every repair the pipeline makes so it can be published."""

    def __init__(self) -> None:
        self.rows: list[dict[str, object]] = []
        self.raw_shape: tuple[int, int] = (0, 0)
        self.clean_shape: tuple[int, int] = (0, 0)

    def add(self, step: str, column: str, issue: str, action: str, affected: int) -> None:
        self.rows.append(
            {
                "Step": step,
                "Column": column,
                "Issue found": issue,
                "Action taken": action,
                "Rows affected": affected,
            }
        )
        print(f"    - {column:<22} {issue:<38} {affected:>7,} rows")

    def to_markdown(self) -> str:
        headers = ["Step", "Column", "Issue found", "Action taken", "Rows affected"]
        table_lines = [
            "| " + " | ".join(headers) + " |",
            "|" + "|".join(["---"] * len(headers)) + "|",
        ]
        for row in self.rows:
            cells = [str(row[h]) for h in headers[:-1]]
            cells.append(f"{row['Rows affected']:,}")
            table_lines.append("| " + " | ".join(cells) + " |")

        lines = [
            "# Data Quality Report - Luxury Housing Bengaluru",
            "",
            "Generated by `python_scripts/data_cleaning.py`.",
            "",
            "## Summary",
            "",
            f"- **Raw dataset:** {self.raw_shape[0]:,} rows x {self.raw_shape[1]} columns",
            f"- **Cleaned dataset:** {self.clean_shape[0]:,} rows x {self.clean_shape[1]} columns",
            f"- **Distinct repairs applied:** {len(self.rows)}",
            "",
            "## Repairs applied",
            "",
            *table_lines,
            "",
        ]
        return "\n".join(lines)


# --------------------------------------------------------------------------
# Load
# --------------------------------------------------------------------------
def load_raw_data(path: Path = cfg.RAW_CSV) -> pd.DataFrame:
    """Load the raw CSV as plain strings so no silent coercion happens first."""
    if not path.exists():
        raise FileNotFoundError(
            f"Raw dataset not found at {path}.\n"
            "This pipeline runs on the real dataset only - it does not "
            "fabricate sample data."
        )
    df = pd.read_csv(path, dtype=str, keep_default_na=False, na_values=[""])
    print(f"    Loaded {df.shape[0]:,} rows x {df.shape[1]} columns from {path.name}")
    return df


# --------------------------------------------------------------------------
# Cleaning steps
# --------------------------------------------------------------------------
def drop_duplicates(df: pd.DataFrame, report: CleaningReport) -> pd.DataFrame:
    """Remove the 1,000 exactly-duplicated property records."""
    before = len(df)
    df = df.drop_duplicates(ignore_index=True)
    report.add("Deduplicate", "all columns", "Exact duplicate rows",
               "Dropped duplicates, kept first occurrence", before - len(df))

    dupe_ids = int(df["Property_ID"].duplicated().sum())
    if dupe_ids:
        df = df.drop_duplicates(subset="Property_ID", ignore_index=True)
        report.add("Deduplicate", "Property_ID", "Repeated primary key",
                   "Kept first record per Property_ID", dupe_ids)
    return df


def normalise_text(df: pd.DataFrame, report: CleaningReport) -> pd.DataFrame:
    """Collapse the casing variants that inflate the categorical cardinality."""
    # Micro_Market: 'jp nagar' / 'Jp Nagar' / 'JP NAGAR' are one market.
    before = df["Micro_Market"].nunique()
    df["Micro_Market"] = (
        df["Micro_Market"].str.strip().str.title().replace(cfg.MICRO_MARKET_FIXES)
    )
    report.add("Normalise text", "Micro_Market",
               f"{before} casing variants of {df['Micro_Market'].nunique()} markets",
               "Title-cased and mapped acronyms (JP Nagar, MG Road)",
               before - df["Micro_Market"].nunique())

    # Configuration: '3bhk' / '3Bhk' / '3BHK' and the '5bhk+' family.
    before = df["Configuration"].nunique()
    df["Configuration"] = (
        df["Configuration"].str.strip().str.upper().str.replace(" ", "", regex=False)
    )
    report.add("Normalise text", "Configuration",
               f"{before} casing variants of {df['Configuration'].nunique()} layouts",
               "Upper-cased to 3BHK / 4BHK / 5BHK+",
               before - df["Configuration"].nunique())

    # Possession_Status: 'Under construction' -> 'Under Construction'.
    before = df["Possession_Status"].nunique()
    df["Possession_Status"] = (
        df["Possession_Status"].str.strip().str.title().replace(cfg.POSSESSION_FIXES)
    )
    report.add("Normalise text", "Possession_Status", "Inconsistent sentence casing",
               "Title-cased to Launch / Under Construction / Ready to Move",
               int(df["Possession_Status"].notna().sum()))

    # Remaining label columns: whitespace only.
    for column in ("Developer_Name", "Project_Name", "Transaction_Type",
                   "Buyer_Type", "Sales_Channel"):
        df[column] = df[column].str.strip()

    # NRI_Buyer: 'yes'/'no' -> 'Yes'/'No' so it reads cleanly in a slicer.
    df["NRI_Buyer"] = df["NRI_Buyer"].str.strip().str.capitalize()
    report.add("Normalise text", "NRI_Buyer", "Lower-case yes/no flags",
               "Capitalised to Yes / No", len(df))
    return df


def parse_ticket_price(df: pd.DataFrame, report: CleaningReport) -> pd.DataFrame:
    """Turn the mixed '12.75' / '₹12.75 Cr' price column into a float."""
    raw = df["Ticket_Price_Cr"]

    currency_formatted = int(raw.str.contains("Cr", case=False, na=False).sum())
    stripped = (
        raw.str.replace("₹", "", regex=False)      # rupee sign
           .str.replace(",", "", regex=False)
           .str.replace(r"\s*Cr\s*$", "", regex=True, case=False)
           .str.strip()
    )
    price = pd.to_numeric(stripped, errors="coerce")
    report.add("Parse numerics", "Ticket_Price_Cr", "Prices stored as '₹12.75 Cr' text",
               "Stripped currency symbol and unit, cast to float", currency_formatted)

    invalid = int((price <= 0).sum())
    price = price.mask(price <= 0)
    report.add("Parse numerics", "Ticket_Price_Cr", "Zero or negative prices",
               "Set to null, then imputed", invalid)

    df["Ticket_Price_Cr"] = price
    return df


def parse_unit_size(df: pd.DataFrame, report: CleaningReport) -> pd.DataFrame:
    """Cast unit size to float and treat the -1 sentinel as missing."""
    size = pd.to_numeric(df["Unit_Size_Sqft"], errors="coerce")

    sentinels = int((size <= 0).sum())
    size = size.mask(size <= 0)
    report.add("Parse numerics", "Unit_Size_Sqft", "'-1' used as a missing-value sentinel",
               "Converted to null, then imputed", sentinels)

    df["Unit_Size_Sqft"] = size
    return df


def parse_scores(df: pd.DataFrame, report: CleaningReport) -> pd.DataFrame:
    """Cast the four score/time columns to numeric."""
    for column in ("Amenity_Score", "Connectivity_Score", "Locality_Infra_Score"):
        df[column] = pd.to_numeric(df[column], errors="coerce").round(2)
    df["Avg_Traffic_Time_Min"] = pd.to_numeric(
        df["Avg_Traffic_Time_Min"], errors="coerce"
    ).astype("Int64")
    report.add("Parse numerics", "Score columns", "Stored as text",
               "Cast Amenity / Connectivity / Locality scores and traffic time to numeric",
               len(df))
    return df


def flag_price_outliers(df: pd.DataFrame, report: CleaningReport) -> pd.DataFrame:
    """
    Flag implausible ticket prices with the IQR rule.

    The raw file has a bulk of genuine prices around 3-20 Cr plus injected
    spikes at exactly 60, 70 and 100 Cr. Outliers are flagged rather than
    deleted so the dashboard can include or exclude them deliberately, but they
    are held out of the imputation medians so they cannot skew the fill values.
    """
    price = df["Ticket_Price_Cr"]
    q1, q3 = price.quantile(0.25), price.quantile(0.75)
    upper = q3 + 1.5 * (q3 - q1)

    df["Is_Price_Outlier"] = (price > upper).fillna(False).astype(int)
    report.add("Outliers", "Ticket_Price_Cr",
               f"Values above the IQR upper fence of {upper:.2f} Cr",
               "Flagged in Is_Price_Outlier, retained in the dataset",
               int(df["Is_Price_Outlier"].sum()))
    return df


def _group_median_fill(
    df: pd.DataFrame, column: str, keys: list[list[str]], mask: pd.Series | None = None
) -> pd.Series:
    """Fill nulls with progressively coarser group medians, then the global median."""
    source = df[column].mask(mask) if mask is not None else df[column]
    filled = df[column]
    for key in keys:
        medians = source.groupby([df[k] for k in key]).transform("median")
        filled = filled.fillna(medians)
    return filled.fillna(source.median())


def impute_missing(df: pd.DataFrame, report: CleaningReport) -> pd.DataFrame:
    """
    Fill the three numeric gaps with group medians rather than a global mean.

    Price and size vary systematically by market and layout, so a
    (Micro_Market, Configuration) median is a far better estimate than one
    number for the whole city. Each imputation is recorded in an audit flag so
    downstream analysis can exclude synthetic values if needed.
    """
    outlier_mask = df["Is_Price_Outlier"] == 1

    df["Price_Imputed"] = df["Ticket_Price_Cr"].isna().astype(int)
    missing = int(df["Price_Imputed"].sum())
    df["Ticket_Price_Cr"] = _group_median_fill(
        df, "Ticket_Price_Cr",
        [["Micro_Market", "Configuration"], ["Micro_Market"], ["Configuration"]],
        mask=outlier_mask,
    ).round(2)
    report.add("Impute", "Ticket_Price_Cr", "Missing prices",
               "Filled with Micro_Market x Configuration median (outliers excluded)",
               missing)

    df["Size_Imputed"] = df["Unit_Size_Sqft"].isna().astype(int)
    missing = int(df["Size_Imputed"].sum())
    df["Unit_Size_Sqft"] = _group_median_fill(
        df, "Unit_Size_Sqft",
        [["Micro_Market", "Configuration"], ["Configuration"]],
    ).round(0)
    report.add("Impute", "Unit_Size_Sqft", "Missing unit sizes (incl. -1 sentinels)",
               "Filled with Micro_Market x Configuration median", missing)

    df["Amenity_Imputed"] = df["Amenity_Score"].isna().astype(int)
    missing = int(df["Amenity_Imputed"].sum())
    df["Amenity_Score"] = _group_median_fill(
        df, "Amenity_Score", [["Micro_Market"]]
    ).round(2)
    report.add("Impute", "Amenity_Score", "Missing amenity scores",
               "Filled with Micro_Market median", missing)

    missing = int(df["Buyer_Comments"].isna().sum())
    df["Buyer_Comments"] = df["Buyer_Comments"].fillna(cfg.NO_COMMENT)
    report.add("Impute", "Buyer_Comments", "Missing buyer feedback",
               f"Filled with '{cfg.NO_COMMENT}' so the category stays visible", missing)
    return df


# --------------------------------------------------------------------------
# Feature engineering
# --------------------------------------------------------------------------
def engineer_features(df: pd.DataFrame, report: CleaningReport) -> pd.DataFrame:
    """Derive the analytical columns the SQL warehouse and dashboard consume."""

    # Price per square foot: crores -> rupees, divided by area.
    df["Price_per_Sqft"] = (df["Ticket_Price_Cr"] * 1e7 / df["Unit_Size_Sqft"]).round(2)
    report.add("Feature", "Price_per_Sqft", "Not present in raw data",
               "Derived as Ticket_Price_Cr x 1e7 / Unit_Size_Sqft", len(df))

    # Calendar features from the quarter-end date.
    quarter = pd.to_datetime(df["Purchase_Quarter"], errors="coerce")
    df["Purchase_Date"] = quarter.dt.date
    df["Purchase_Year"] = quarter.dt.year.astype("Int64")
    df["Quarter_Number"] = quarter.dt.quarter.astype("Int64")
    df["Quarter_Label"] = (
        quarter.dt.year.astype("Int64").astype(str) + "-Q" +
        quarter.dt.quarter.astype("Int64").astype(str)
    )
    # Indian fiscal year runs April -> March.
    fy_start = np.where(quarter.dt.month >= 4, quarter.dt.year, quarter.dt.year - 1)
    df["Fiscal_Year"] = [f"FY{y}-{str(y + 1)[-2:]}" for y in fy_start]
    report.add("Feature", "Purchase_Quarter", "Only a raw quarter-end date",
               "Derived Purchase_Year, Quarter_Number, Quarter_Label and Fiscal_Year",
               len(df))

    # Booking signal.
    #
    # ASSUMPTION: the brief names a Booking_Status column, but the raw file has
    # no such column. Transaction_Type is the only booking-related field, so a
    # Primary transaction (a sale direct from the developer) is treated as a
    # booking and a Secondary transaction (resale) is not.
    df["Booking_Flag"] = (df["Transaction_Type"] == "Primary").astype(int)
    df["Booking_Status"] = np.where(df["Booking_Flag"] == 1, "Booked", "Not Booked")
    report.add("Feature", "Booking_Flag / Booking_Status",
               "No Booking_Status column exists in the raw file",
               "Derived from Transaction_Type: Primary = Booked, Secondary = Not Booked",
               int(df["Booking_Flag"].sum()))

    # Buyer sentiment from the closed set of canned comments.
    df["Comment_Sentiment"] = (
        df["Buyer_Comments"].map(cfg.COMMENT_SENTIMENT).fillna(cfg.NO_COMMENT)
    )
    report.add("Feature", "Comment_Sentiment", "Free-text buyer feedback",
               "Mapped the 9 canned comments to Positive / Negative / Neutral",
               int((df["Comment_Sentiment"] != cfg.NO_COMMENT).sum()))

    # Geography, so map visuals do not depend on name geocoding.
    coords = df["Micro_Market"].map(cfg.MICRO_MARKET_COORDS)
    df["Latitude"] = coords.map(lambda c: c[0] if isinstance(c, tuple) else None)
    df["Longitude"] = coords.map(lambda c: c[1] if isinstance(c, tuple) else None)
    df["Map_Location"] = df["Micro_Market"] + ", " + cfg.CITY_QUALIFIER
    unmapped = int(df["Latitude"].isna().sum())
    report.add("Feature", "Latitude / Longitude", "No coordinates in raw data",
               "Joined approximate locality centroids for all 16 micro-markets",
               len(df) - unmapped)
    if unmapped:
        raise AssertionError(
            f"{unmapped} rows have a micro-market with no coordinate entry. "
            "Add it to config.MICRO_MARKET_COORDS."
        )

    # Analytical bands.
    df["Price_Segment"] = pd.cut(
        df["Ticket_Price_Cr"],
        bins=[0, 10, 15, 25, np.inf],
        labels=["Entry Luxury (<10 Cr)", "Premium (10-15 Cr)",
                "Ultra Luxury (15-25 Cr)", "Elite (25 Cr+)"],
    )
    df["Size_Category"] = pd.cut(
        df["Unit_Size_Sqft"],
        bins=[0, 4500, 6000, 7500, np.inf],
        labels=["Compact (<4.5k)", "Mid-Size (4.5-6k)",
                "Large (6-7.5k)", "Ultra Large (7.5k+)"],
    )
    df["Amenity_Band"] = pd.cut(
        df["Amenity_Score"],
        bins=[0, 6.5, 8.0, 10.0],
        labels=["Low", "Medium", "High"],
    )
    report.add("Feature", "Segment bands", "Continuous values only",
               "Binned into Price_Segment, Size_Category and Amenity_Band", len(df))
    return df


def finalise(df: pd.DataFrame) -> pd.DataFrame:
    """Order columns logically and sort by property id."""
    ordered = [
        # Identity
        "Property_ID", "Project_Name", "Developer_Name", "Micro_Market",
        # Geography
        "Latitude", "Longitude", "Map_Location",
        # Unit
        "Configuration", "Unit_Size_Sqft", "Size_Category",
        # Commercials
        "Ticket_Price_Cr", "Price_per_Sqft", "Price_Segment", "Is_Price_Outlier",
        # Transaction
        "Transaction_Type", "Booking_Flag", "Booking_Status", "Possession_Status",
        "Sales_Channel",
        # Buyer
        "Buyer_Type", "NRI_Buyer", "Buyer_Comments", "Comment_Sentiment",
        # Location quality
        "Amenity_Score", "Amenity_Band", "Connectivity_Score",
        "Locality_Infra_Score", "Avg_Traffic_Time_Min",
        # Time
        "Purchase_Date", "Purchase_Year", "Quarter_Number", "Quarter_Label",
        "Fiscal_Year",
        # Audit
        "Price_Imputed", "Size_Imputed", "Amenity_Imputed",
    ]
    return df[ordered].sort_values("Property_ID", ignore_index=True)


def validate(df: pd.DataFrame) -> None:
    """Assert the invariants the warehouse depends on."""
    print("\n[7/8] Validating cleaned dataset...")
    checks = {
        "No duplicate Property_ID": not df["Property_ID"].duplicated().any(),
        "No nulls in Ticket_Price_Cr": df["Ticket_Price_Cr"].notna().all(),
        "No nulls in Unit_Size_Sqft": df["Unit_Size_Sqft"].notna().all(),
        "No nulls in Amenity_Score": df["Amenity_Score"].notna().all(),
        "All prices positive": (df["Ticket_Price_Cr"] > 0).all(),
        "All unit sizes positive": (df["Unit_Size_Sqft"] > 0).all(),
        "Booking_Flag is binary": set(df["Booking_Flag"].unique()) <= {0, 1},
        "Quarter_Number in 1-4": df["Quarter_Number"].between(1, 4).all(),
        "Configuration collapsed to 3": df["Configuration"].nunique() == 3,
        "Micro_Market collapsed to 16": df["Micro_Market"].nunique() == 16,
        "Every row has coordinates": df[["Latitude", "Longitude"]].notna().all().all(),
        "Coordinates inside Bengaluru": (
            df["Latitude"].between(12.7, 13.2).all()
            and df["Longitude"].between(77.4, 77.8).all()
        ),
    }
    for name, passed in checks.items():
        print(f"    [{'PASS' if passed else 'FAIL'}] {name}")
    failed = [name for name, passed in checks.items() if not passed]
    if failed:
        raise AssertionError(f"Validation failed: {failed}")


def summarise(df: pd.DataFrame) -> None:
    """Print the headline numbers a reviewer will want to see."""
    print("\n" + "=" * 74)
    print("CLEANED DATASET SUMMARY")
    print("=" * 74)
    core = df[df["Is_Price_Outlier"] == 0]
    print(f"  Records                : {len(df):,}")
    print(f"  Developers             : {df['Developer_Name'].nunique()}")
    print(f"  Micro-markets          : {df['Micro_Market'].nunique()}")
    print(f"  Date range             : {df['Purchase_Date'].min()} to {df['Purchase_Date'].max()}")
    print(f"  Avg ticket price       : Rs {core['Ticket_Price_Cr'].mean():.2f} Cr (outliers excluded)")
    print(f"  Median ticket price    : Rs {core['Ticket_Price_Cr'].median():.2f} Cr")
    print(f"  Avg price per sqft     : Rs {core['Price_per_Sqft'].mean():,.0f}")
    print(f"  Avg unit size          : {df['Unit_Size_Sqft'].mean():,.0f} sqft")
    print(f"  Avg amenity score      : {df['Amenity_Score'].mean():.2f} / 10")
    print(f"  Booking conversion     : {df['Booking_Flag'].mean() * 100:.2f}%")
    print(f"  Positive sentiment     : {(df['Comment_Sentiment'] == 'Positive').mean() * 100:.2f}%")
    print("=" * 74)


# --------------------------------------------------------------------------
# Pipeline
# --------------------------------------------------------------------------
def run() -> pd.DataFrame:
    print("=" * 74)
    print("LUXURY HOUSING - DATA CLEANING PIPELINE")
    print("=" * 74)
    cfg.ensure_dirs()
    report = CleaningReport()

    print("\n[1/8] Loading raw data...")
    df = load_raw_data()
    report.raw_shape = df.shape

    print("\n[2/8] Removing duplicates...")
    df = drop_duplicates(df, report)

    print("\n[3/8] Normalising text fields...")
    df = normalise_text(df, report)

    print("\n[4/8] Parsing numeric fields...")
    df = parse_ticket_price(df, report)
    df = parse_unit_size(df, report)
    df = parse_scores(df, report)
    df = flag_price_outliers(df, report)

    print("\n[5/8] Imputing missing values...")
    df = impute_missing(df, report)

    print("\n[6/8] Engineering features...")
    df = engineer_features(df, report)
    df = finalise(df)
    report.clean_shape = df.shape

    validate(df)

    print("\n[8/8] Writing outputs...")
    df.to_csv(cfg.CLEANED_CSV, index=False)
    print(f"    Cleaned CSV   -> {cfg.CLEANED_CSV}")
    cfg.QUALITY_REPORT.write_text(report.to_markdown(), encoding="utf-8")
    print(f"    Audit report  -> {cfg.QUALITY_REPORT}")

    summarise(df)
    return df


if __name__ == "__main__":
    run()
